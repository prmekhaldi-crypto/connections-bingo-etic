/** Regenerate typed asset access and Markdown indexes after editing asset-manifest.json. */
import fs from "node:fs";
const checkOnly = process.argv.includes("--check");
function writeGenerated(file, content) {
  if (checkOnly) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content)
      throw Error(
        `Generated file is stale: ${file}. Run npm run catalog:generate.`,
      );
  } else fs.writeFileSync(file, content);
}
const list = JSON.parse(fs.readFileSync("etic-ui/asset-manifest.json", "utf8"));
const labels = {
  logos: "Logos",
  icons: "Pictogrammes de contact et réseaux",
  ribbons: "Rubans",
  organic: "Formes libres",
  geometric: "Formes géométriques",
  compositions: "Compositions",
  stickers: "Stickers",
  lettering: "Lettrages fixes",
  cards: "Cartes",
  gradients: "Dégradés officiels",
};
const names = new Set();
for (const a of list) {
  if (names.has(a.name)) throw Error(`Duplicate name: ${a.name}`);
  names.add(a.name);
  if (!fs.existsSync("etic-ui/assets/" + a.path))
    throw Error(`Missing: ${a.path}`);
}
const keys = list.flatMap((asset, index) =>
  [asset.name, ...(asset.aliases ?? [])].map((name) => ({ name, index })),
);
if (new Set(keys.map((k) => k.name)).size !== keys.length)
  throw Error("Duplicate asset name or alias");
const imports = list.map(
  (a, i) => `import asset${i} from ${JSON.stringify("./assets/" + a.path)};`,
);
const code = [
  "// Generated by scripts/update-catalog.mjs. Edit asset-manifest.json, then regenerate.",
  ...imports,
  "",
  "export const brandAssets = {",
  ...keys.map((k) => `  ${JSON.stringify(k.name)}: asset${k.index},`),
  "} as const;",
  "export type BrandAssetName = keyof typeof brandAssets;",
  "export const brandAssetInfo = {",
  ...keys.map((k) => {
    const a = list[k.index];
    return `  ${JSON.stringify(k.name)}: ${JSON.stringify({ width: a.width, height: a.height, role: a.role, kind: a.kind ?? "artwork", ribbonFamily: a.ribbonFamily ?? null })},`;
  }),
  "} as const;",
  "export type BrandArtworkName = { [K in BrandAssetName]: typeof brandAssetInfo[K]['role'] extends 'artwork' | 'icon' ? K : never }[BrandAssetName];",
  "export const ribbonsByFamily = {",
  ...["warm", "cool", "neutral"].map(
    (family) =>
      `  ${family}: ${JSON.stringify(list.filter((a) => a.category === "ribbons" && a.ribbonFamily === family).map((a) => a.name))},`,
  ),
  "} as const;",
  "export type RibbonFamily = 'warm' | 'cool';",
  "export type RibbonName<F extends RibbonFamily> = typeof ribbonsByFamily[F][number];",
  "export const brandAssetIndex = [",
  ...list.map((a, i) => `  { ...${JSON.stringify(a)}, src: asset${i} },`),
  "] as const;",
  'export type BrandAssetCategory = typeof brandAssetIndex[number]["category"];',
  "",
];
writeGenerated("etic-ui/catalog.ts", code.join("\n"));
fs.mkdirSync("docs/assets", { recursive: true });
const intro = [
  "# Catalogue des assets ETIC",
  "",
  `${list.length} fichiers graphiques locaux. Les aperçus ci-dessous sont des documents Markdown, pas un site. Chaque fichier possède une source, des dimensions et un usage dans [le manifeste](../etic-ui/asset-manifest.json).`,
  "",
  "| Famille | Fichiers | Catalogue |",
  "| --- | ---: | --- |",
];
for (const cat of Object.keys(labels)) {
  const rows = list.filter((a) => a.category === cat);
  if (!rows.length) continue;
  intro.push(
    `| ${labels[cat]} | ${rows.length} | [Ouvrir](assets/${cat}.md) |`,
  );
  const md = [
    `# ${labels[cat]}`,
    "",
    "[Retour au catalogue](../assets.md)",
    "",
  ];
  if (fs.existsSync(`docs/brand/contact-sheets/${cat}.webp`))
    md.push(
      `![Sélection de cette famille ; tous les fichiers sont détaillés ci-dessous](../brand/contact-sheets/${cat}.webp)`,
      "",
    );
  for (const a of rows) {
    const pairing = a.pairingGuidance;
    const pairingLines = pairing
      ? [
          "**Association de composition (direction du projet, pas nouvelle règle officielle)**",
          "",
          pairing.prefer,
          "",
          `À éviter : ${pairing.avoid}`,
          ...(pairing.alternativeForRed ? ["", pairing.alternativeForRed] : []),
          "",
        ]
      : [];
    md.push(
      `## ${a.name}`,
      "",
      `<img src="../../etic-ui/assets/${a.path}" width="160" alt="${a.name}">`,
      "",
      a.usage,
      "",
      ...(a.ribbonFamily
        ? [
            `- Famille de rubans : **${a.ribbonFamily}**. Garder une seule famille colorée sur toute la page.`,
            "",
          ]
        : []),
      ...(a.kind ? [`- Niveau : **${a.kind}**`, ""] : []),
      ...(a.aliases?.length
        ? [
            `- Anciens noms d’import conservés : ${a.aliases.map((n) => `\`${n}\``).join(", ")}`,
            "",
          ]
        : []),
      ...(a.extraction?.rect
        ? [
            `- Fenêtre de découpe source (x, y, largeur, hauteur) : ${a.extraction.rect.join(", ")}`,
            "",
          ]
        : []),
      ...pairingLines,
      `- Fichier : [${a.path}](../../etic-ui/assets/${a.path})`,
      `- Format : ${a.format.toUpperCase()}, ${a.width} × ${a.height} px, ${(a.bytes / 1024).toFixed(1)} Ko`,
      `- [Source Figma ${a.nodeId}](${a.source})`,
      "",
    );
  }
  writeGenerated(`docs/assets/${cat}.md`, md.join("\n"));
}
intro.push(
  "",
  "## Choisir rapidement",
  "",
  "- **Logo institutionnel** : `etic-color` ou `etic-white`, via le composant `Logo`.",
  "- **Rubans** : choisir warm OU cool pour toute la page, puis consulter ribbons/ ; vagues, slogans et grands rubans y sont regroupés. neutral contient le trait noir.",
  "- **Visuel plus expressif** : une composition ou un motif géométrique dans un espace dédié.",
  "- **Message de club** : sticker ou lettrage existant, sans réinterpréter le logo.",
  "- **Contenu interactif** : `BrandCard`, avec du vrai HTML ; les images de cartes restent des références/surfaces.",
  "",
  "Les stickers illustrent des compositions spécifiques ; leurs variations ne donnent pas la permission de recolorer le logo de base. Les lettrages « LOGO » et « variation » sont des titres de planche, explicitement séparés des logos.",
  "",
  "## Utilisation",
  "",
  "```tsx",
  "import { BrandArtwork, brandAssets } from './etic-ui';",
  '<BrandArtwork name="ribbon-cool-loop-01" width={180} />',
  '<img src={brandAssets["dots-nine"]} width={96} alt="" />',
  "```",
  "",
  "Les imports directs des fichiers restent possibles en React ou HTML. Le manifeste fournit les chemins relatifs à `etic-ui/assets/`. Les variantes blanches se consultent sur fond rouge.",
  "",
  "[Parcours de composition](composition-workflow.md) · [Décomposition géométrique](geometry.md) · [Cartes en code](cards.md) · [Dégradés](gradients.md) · [Couverture des 33 planches](charter-coverage.md) · [Méthode et limites](extraction.md)",
  "",
);
writeGenerated("docs/assets.md", intro.join("\n"));
const boards = JSON.parse(
  fs.readFileSync("docs/brand/board-inventory.json"),
).boards.sort(
  (a, b) => Number(a.name.split(" ")[1]) - Number(b.name.split(" ")[1]),
);
const audit = [
  "# Couverture de la charte",
  "",
  "Les 33 planches ont été inspectées. Elles sont archivées ici comme références visuelles, distinctes des assets détachés de `etic-ui/assets/`. Les templates sociaux et les mockups servent à comprendre la composition ; ils ne sont pas des interfaces web aplaties à réutiliser.",
  "",
  "| Planche | Source | Aperçu |",
  "| --- | --- | --- |",
];
for (const b of boards) {
  const n = Number(b.name.split(" ")[1]);
  const topic =
    n <= 5
      ? "Introduction"
      : n <= 10
        ? "Logotype"
        : n <= 15
          ? "Palette et combinaisons"
          : n <= 20
            ? "Typographie"
            : n <= 27
              ? "Éléments graphiques"
              : n <= 30
                ? "Réseaux sociaux"
                : "Papeterie et stickers";
  audit.push(
    `| ${b.name} · ${topic} | [${b.id}](https://www.figma.com/design/eofQFq1bCM8Ooe5KXBDRsk?node-id=${b.id.replace(":", "-")}) | [Ouvrir](brand/boards/${b.id.replace(":", "-")}.webp) |`,
  );
}
audit.push(
  "",
  "## Exceptions explicites",
  "",
  "- Les doublons de la même forme présents sur plusieurs pages ne constituent pas nécessairement un nouvel asset. Les occurrences sources restent consultables dans les planches.",
  "- Les nœuds masqués 1:1255 et 1:1535 sont inventoriés, sans être présentés comme éléments actifs de la charte.",
  "- Le groupe de fond 1:1158 ne rend que son rectangle rouge lors de l’export isolé. Cet export incomplet n’est pas livré comme décor.",
  "- Les copies isolées 1:131, 1:132, 1:133 et 1:6068 restent vides via le MCP. Six pictogrammes complets ont été retrouvés dans le banner : 1:97, 1:102, 1:107, 1:112, 1:117, 1:123. Ils sont livrés dans icons/, sans reconstruction.",
  "- Les textes éditoriaux, numéros de chapitre, mocks d’Instagram et mauvaises utilisations du logo restent dans les références ; ils ne sont pas proposés comme composants ou variantes officielles.",
  "- Aucun fichier de police redistribuable n’a été obtenu.",
  "",
  "[Direction artistique](art-direction.md) · [Revue d’exhaustivité](audit.md)",
  "",
  "[Inventaire des exports](brand/export-inventory.json) · [Index des planches et calques hors charte](brand/board-inventory.json)",
  "",
);
writeGenerated("docs/charter-coverage.md", audit.join("\n"));
console.log(
  `Catalogue ${checkOnly ? "verified" : "generated"}: ${list.length} typed assets and ${Object.keys(labels).length} family indexes.`,
);

writeGenerated(
  "docs/assets/waves.md",
  "# Courbes et rubans avec slogans\n\nCes éléments sont regroupés dans [le catalogue des rubans](ribbons.md) et dans `etic-ui/assets/ribbons/`, par famille chromatique. Les noms d’import TypeScript existants sont conservés.\n",
);
for (const category of ["ribbons", "geometric"]) {
  const base = `etic-ui/assets/${category}`;
  const assetRows = list.filter((a) => a.category === category);
  const groups =
    category === "ribbons"
      ? ["warm", "cool", "neutral"]
      : ["primitive", "module", "composition"];
  const text = [
    category === "ribbons" ? "# Rubans ETIC" : "# Géométries ETIC",
    "",
    category === "ribbons"
      ? "**Une seule famille de rubans colorés par page : warm OU cool.** neutral désigne le trait noir. Les vagues, slogans et grands rubans sont aussi rangés ici. Aucune recoloration artificielle n’est proposée pour fabriquer des variantes absentes de Figma."
      : "**Choisir le bon niveau de décomposition.** Une primitive est une forme seule ; un module conserve l’assemblage et la découpe d’origine ; une composition réunit plusieurs modules. Utiliser module-warm-square pour le carré central de la charte, et non double-disc-warm-free.",
    "",
    `[Guide détaillé](../../../docs/${category === "ribbons" ? "composition-workflow" : "geometry"}.md) · [Manifeste](../../asset-manifest.json)`,
    "",
  ];
  for (const group of groups) {
    text.push(`## ${group}`, "");
    for (const a of assetRows.filter((a) =>
      category === "ribbons" ? a.ribbonFamily === group : a.kind === group,
    )) {
      const relative = a.path.slice(category.length + 1);
      text.push(
        `### ${a.name}`,
        "",
        `<img src="${relative}" width="140" alt="${a.name}">`,
        "",
        a.usage,
        "",
        `[Fichier](${relative}) · [Source ${a.nodeId}](${a.source})`,
        "",
      );
    }
  }
  writeGenerated(`${base}/README.md`, text.join("\n"));
}
